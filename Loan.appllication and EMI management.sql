CREATE OR REPLACE PROCEDURE CLASSIFY_LOAN(
    P_LOAN_ID NUMBER
)
IS
    V_CIBIL_SCORE NUMBER;
BEGIN
    SELECT CIBIL_SCORE
    INTO V_CIBIL_SCORE
    FROM LOAN_APPLICATIONS
    WHERE LOAN_ID = P_LOAN_ID;

    IF V_CIBIL_SCORE >= 750 THEN
        DBMS_OUTPUT.PUT_LINE('Classification: EXCELLENT');
    ELSIF V_CIBIL_SCORE >= 650 THEN
        DBMS_OUTPUT.PUT_LINE('Classification: GOOD');
    ELSIF V_CIBIL_SCORE >= 550 THEN
        DBMS_OUTPUT.PUT_LINE('Classification: AVERAGE');
    ELSE
        DBMS_OUTPUT.PUT_LINE('Classification: POOR');
    END IF;

EXCEPTION
    WHEN NO_DATA_FOUND THEN
        DBMS_OUTPUT.PUT_LINE('Invalid Loan ID');
END;
SET SERVEROUTPUT ON;

